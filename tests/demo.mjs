// Node 20+; no packages. Tests the standalone data adapter, not browser rendering.
import assert from 'node:assert/strict';
const storage = new Map();
globalThis.localStorage = { getItem: k => storage.get(k) ?? null, setItem: (k, v) => storage.set(k, v) };
let networkCalls = 0;
globalThis.fetch = () => { networkCalls++; throw new Error('Demo must not call a backend'); };
const { api, isDemo, resetDemo } = await import('../docs/js/data.js');
let count = 0;
const check = (value, name) => { assert.ok(value, name); count++; console.log('PASS', name); };
check(isDemo, 'Demo mode is explicit');
const sessions = await api.list('sessions');
check(sessions.length === 6 && (await api.list('students')).length === 12, 'Six sessions and twelve fictional students');
const before = sessions[0].participantCount;
const student = await api.create('students', { fullName: 'تست', email: 'test@example.com', isActive: true });
check((await api.list('sessions'))[0].participantCount === before, 'New student does not change old rosters');
await api.update('students', student.id, { fullName: 'نام جدید', email: 'test@example.com', isActive: true });
check((await api.list('students')).find(s => s.id === student.id).fullName === 'نام جدید', 'Student update');
await assert.rejects(() => api.create('students', { fullName: 'تست', email: 'TEST@example.com', isActive: true }));
check(true, 'Duplicate email rejected');
const teacher = await api.create('instructors', { fullName: 'مدرس', email: 'newteacher@example.com', expertise: 'C#', isActive: true });
await api.update('instructors', teacher.id, { fullName: 'مدرس جدید', email: 'newteacher@example.com', expertise: 'EF Core', isActive: true });
check((await api.list('instructors')).find(t => t.id === teacher.id).expertise === 'EF Core', 'Instructor create/update');
const session = await api.create('sessions', { title: 'جلسه تست', date: '2026-11-26', instructorId: teacher.id, taskDescription: '', progressPercent: 50, isCompleted: true, studentIds: [student.id] });
await api.attendance(session.id, [{ studentId: student.id, status: 'Present' }]);
check((await api.list('sessions')).find(s => s.id === session.id).attendancePercent === 100, 'Attendance calculates 100 percent');
await assert.rejects(() => api.attendance(session.id, []));
await assert.rejects(() => api.attendance(session.id, [{studentId: student.id, status: 'bad'}]));
check((await api.list('sessions')).find(s => s.id === session.id).attendancePercent === 100, 'Invalid attendance preserves state');
const evaluation = await api.create('evaluations', { sessionId: session.id, studentId: student.id, instructorId: teacher.id, score: 80, notes: 'تست' });
await api.update('evaluations', evaluation.id, { sessionId: session.id, studentId: student.id, instructorId: teacher.id, score: 90, notes: 'ویرایش' });
check((await api.list('evaluations')).find(e => e.id === evaluation.id).score === 90, 'Evaluation create/update');
await assert.rejects(() => api.create('evaluations', { sessionId: session.id, studentId: student.id, instructorId: teacher.id, score: 80, notes: '' }));
check(true, 'Duplicate evaluation rejected');
await assert.rejects(() => api.remove('students', student.id));
await assert.rejects(() => api.remove('instructors', teacher.id));
check(true, 'History prevents deleting referenced people');
const reload = await import('../docs/js/data.js?reload');
check((await reload.api.list('students')).some(s => s.id === student.id), 'Data loads from simulated localStorage after module reload');
await api.remove('evaluations', evaluation.id);
check(!(await api.list('evaluations')).some(e => e.id === evaluation.id), 'Evaluation delete');
await api.create('evaluations', { sessionId: session.id, studentId: student.id, instructorId: teacher.id, score: 80, notes: '' });
await api.remove('sessions', session.id);
check(!(await api.list('evaluations')).some(e => e.sessionId === session.id), 'Session deletion cascades to evaluations');
await api.remove('students', student.id); await api.remove('instructors', teacher.id);
check(!(await api.list('students')).some(s => s.id === student.id), 'Unreferenced people can be deleted');
const originalSet = localStorage.setItem;
localStorage.setItem = () => { throw new Error('Quota'); };
await assert.rejects(() => api.create('students', {fullName:'Fail',email:'fail@example.com',isActive:true}));
check(!(await api.list('students')).some(s => s.email === 'fail@example.com'), 'Storage failure rolls back in-memory mutation');
localStorage.setItem = originalSet;
await resetDemo();
check((await api.list('students')).length === 12 && (await api.list('sessions')).length === 6, 'Reset restores fictional data');
check(networkCalls === 0, 'Demo never calls Fetch or the backend');
console.log(`\n${count} checks passed. No browser rendering was tested.`);
